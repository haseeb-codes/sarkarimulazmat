<article class="mx-auto max-w-2xl space-y-4">
	<h1>About Sarkari Mulazmat</h1>
	<p class="text-muted-foreground">Government jobs in Pakistan — filter by your background.</p>

	<p class="text-sm leading-relaxed">
		Sarkari Mulazmat is an informational portal that helps you find government job openings across
		Pakistan. We gather eligibility details from public advertisements so you can quickly see which
		roles match your education, age, domicile, and other criteria — without reading every ad from
		scratch.
	</p>

	<p class="text-sm leading-relaxed">
		We do not hire for these roles and are not the recruiting body. Always confirm deadlines,
		requirements, and how to apply on the official advertisement before you submit an application.
	</p>

	<h2>How to search</h2>
	<p class="text-sm leading-relaxed">
		Start on the
		<a href="/" class="text-primary underline-offset-2 hover:underline">home page</a>
		. Use the search box for keywords (job title, department, or skill), then narrow results with
		filters. On mobile, open the filters drawer; on larger screens the same options appear beside
		the list.
	</p>

	<ul class="list-disc space-y-2 pl-5 text-sm leading-relaxed">
		<li>
			<strong>Keywords</strong> — type a title, organization, or topic to find matching postings.
		</li>
		<li>
			<strong>BPS grade</strong> — limit results to a specific scale (for example BPS-14 or
			BPS-17).
		</li>
		<li>
			<strong>Max age</strong> — keep only jobs you are still eligible for by age.
		</li>
		<li>
			<strong>Domicile</strong> — filter by province or region when the ad restricts who can apply.
		</li>
		<li>
			<strong>Qualification level</strong> — Matric, Intermediate, Bachelor’s, Master’s, and
			similar levels.
		</li>
		<li>
			<strong>Degree specialization</strong> — pick fields of study (for example Computer Science
			or Public Administration) so unrelated openings drop out.
		</li>
		<li>
			<strong>Job type &amp; quotas</strong> — permanent posts only, women-only roles, and
			minority, transgender, or disability quota openings when those apply.
		</li>
		<li>
			<strong>Include expired</strong> — turn this on if you want to review closed ads as well as
			open ones.
		</li>
	</ul>

	<h2>Browse by category</h2>
	<p class="text-sm leading-relaxed">
		Besides filters, you can browse curated groups — by posting organization, advertisement date,
		gender eligibility, degree area, and more. The
		<a href="/tags" class="text-primary underline-offset-2 hover:underline">Tags</a>
		page is another quick way to jump into popular groupings.
	</p>

	<h2>Job details</h2>
	<p class="text-sm leading-relaxed">
		Open any listing to see eligibility summary, closing date, and a link or view of the original
		ad when available. Use that official source for the final word on how and when to apply.
	</p>
