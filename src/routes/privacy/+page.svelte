	<h2>What we collect</h2>
	<ul class="list-disc space-y-2 pl-5 text-sm leading-relaxed">
		<li>
			<strong>Search filters</strong> — when you filter jobs (degree area, education, grade, age,
			location, keywords), we may log those filters and the result count to understand which
			searches are useful. We do not intend this as personal profiling.
		</li>
		<li>
			<strong>Visitor cookie</strong> — a first-party <code>visitor_id</code> cookie (HTTP-only)
			lets us tell first-time from returning visitors and save anonymous search preferences. It is
			not used for advertising.
		</li>
		<li>
			<strong>Account profile</strong> (optional, if you sign in) — email via Google sign-in, date
			of birth, education, and specialization, only with your explicit consent, so we can match
			jobs and send digests you opted into.
		</li>
	</ul>

	<h2>Google sign-in</h2>
	<p class="text-sm leading-relaxed">
		If you choose Google sign-in, we use it only for authentication (to identify your account). We
		do not request access to your Gmail or Google Drive.
	</p>

	<h2>Retention &amp; deletion</h2>
	<p class="text-sm leading-relaxed">
		Search logs are kept for aggregate analysis and purged on a rolling schedule (about 12 months).
		You can delete your account from settings once accounts are available; that removes your
		profile and email digest history.
	</p>

